"""Compile sourced basic RF/water parameters; transport and tick scheduling stay native."""
import argparse
import json
import zipfile
import reference
import thermal_catalog

OUTPUT = reference.ROOT / 'mods/era_thermal/reference.lua'


def compile_model(spec):
    if spec['lock_content_sha256'] != reference.read_lock()['content_sha256']:
        raise ValueError('RF model needs the selected pack lock')
    rules = {r['id']: r for r in spec['review']['rules']}
    config = {r['key']: r['value'] for r in spec['config']['facts']}
    for key in ('Dynamo.SmallStorage', 'Machine.SmallStorage', 'Dynamo.CustomPowerScaling',
                'Machine.CustomPowerScaling', 'Machine.CustomEnergyScaling'):
        if config[key] is not False:
            raise ValueError('Unsupported RF scaling/storage configuration')
    def energy(id):
        rule = rules[id]
        return {k: rule[k] for k in ('capacity_rf', 'max_rf_per_tick', 'min_rf_per_tick',
                                     'high_threshold_rf', 'low_threshold_rf', 'ramp')}
    fuels = {r['input']['metadata']: r['energy_rf'] for r in spec['processing_and_fuel']
             if r['machine'] == 'steam_dynamo' and r['input']['kind'] == 'item'
             and r['input']['id'] == 'minecraft:coal'}
    if set(fuels) != {0, 1}:
        raise ValueError('Missing distinct coal/charcoal values')
    generator = energy('dynamo_energy')
    water = rules['steam_water']
    generator.update(tank_mb=water['water_tank_mb'], batch_mb=water['water_batch_mb'],
                     water_credit_rf=water['water_credit_rf'], coal_rf=fuels[0], charcoal_rf=fuels[1])
    iron = [r for r in spec['processing_and_fuel'] if r['machine'] == 'pulverizer'
            and r['input']['id'] == 'oreIron']
    if len(iron) != 1 or iron[0]['output']['id'] != 'dustIron':
        raise ValueError('Unsupported iron processing record')
    return {'schema': 1, 'pack_sha256': spec['lock_content_sha256'],
            'spec_sha256': reference.sha256(reference.canonical(spec)),
            'generator': generator, 'machine': energy('machine_energy'),
            'buffer': {'capacity_rf': config['Storage.Cell.BaseCapacity'],
                       'receive_rf': config['Storage.Cell.BaseReceive'], 'send_rf': config['Storage.Cell.BaseSend']},
            'pulverizer_cost': iron[0]['energy_rf'], 'furnace_cost': rules['dust_smelting']['energy_rf'],
            'ore_multiplier': iron[0]['output']['count']}


def render(value):
    return '-- SPDX-License-Identifier: GPL-3.0-or-later\n-- Generated by scripts/thermal_model.py from the pinned static specification.\nreturn ' + thermal_catalog.lua(value) + '\n'


def verify_sources(fetch=False):
    review = json.loads((reference.ROOT / 'references/thermal-runtime-review.json').read_text())
    lock = reference.read_lock()
    if review['schema'] != 1 or review['pack_sha256'] != lock['content_sha256']:
        raise ValueError('Runtime evidence belongs to a different pack lock')
    entries = {e['path']: e for e in lock['content']['files']}
    for path in sorted({s['jar'] for s in review['evidence']}):
        if fetch:
            reference.fetch_one(entries[path])
        reference.verify(entries[path], reference.destination(entries[path]).read_bytes())
    for source in review['evidence']:
        with zipfile.ZipFile(reference.destination(entries[source['jar']])) as z:
            raw, _ = thermal_catalog.thermal.resource(z, source['entry'], source['jar'])
        if reference.sha256(raw) != source['sha256']:
            raise ValueError('Runtime class review is stale: ' + source['entry'])
    print('RF SOURCE PASS: reviewed TE/RedstoneFlux classes match locked original artifacts')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('check', 'export', 'check-sources', 'fetch-sources'))
    args = parser.parse_args()
    if args.command in ('check-sources', 'fetch-sources'):
        verify_sources(args.command == 'fetch-sources')
        return
    value = render(compile_model(json.loads(thermal_catalog.SPEC.read_text())))
    if args.command == 'export':
        print(value, end='')
    elif value != OUTPUT.read_text():
        raise ValueError('Native RF parameters are stale; regenerate and review')
    else:
        print('RF MODEL PASS: sourced basic RF/water parameters match native definitions')


if __name__ == '__main__':
    main()
