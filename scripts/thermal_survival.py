"""Compile reviewed survival materials and native ore placement; no pack code runs."""
import argparse
import json
import reference
import thermal_catalog as catalog

REVIEW = reference.ROOT / 'references/thermal-survival-review.json'
OUTPUT = reference.ROOT / 'mods/era_materials/survival.lua'


def compile_survival(review, spec, mapping):
    if review['schema'] != 1 or review['pack_sha256'] != spec['lock_content_sha256'] or review['pack_sha256'] != reference.read_lock()['content_sha256']:
        raise ValueError('Survival review needs the selected pack lock')
    ores, scatters = [], []
    for meta, name in sorted(review['ore_identities'].items()):
        if name not in ('tin', 'silver', 'lead') or meta not in ('1', '2', '3'):
            raise ValueError('Unsupported native ore identity')
        ores.append({'name': 'era_materials:' + name + '_ore', 'description': name.title() + ' Ore',
                     'ingot': catalog.mapped('ore:ingot' + name.title(), mapping['mappings'])})
    for name, feature in review['ore_features'].items():
        generator = feature['generator']
        if (feature['distribution'] != 'uniform' or generator['material'] != 'minecraft:stone'
                or feature['dimension'] != {'restriction': 'blacklist', 'value': [-1, 1]}
                or feature['biome'] != 'all'):
            raise ValueError('Unsupported ore distribution or dimension rule')
        lo, hi = feature['min-height'], feature['max-height']
        if type(lo) is not int or type(hi) is not int or not 0 <= lo <= hi <= 255:
            raise ValueError('Unsupported ore height band')
        blocks = generator['block']
        if isinstance(blocks, dict):
            blocks = [blocks]
        total = sum(block.get('weight', 1) for block in blocks)
        for block in blocks:
            if block['name'] != 'thermalfoundation:ore':
                raise ValueError('Unsupported ore block')
            native = review['ore_identities'][str(block['metadata'])]
            weight = catalog.thermal.positive(block.get('weight', 1))
            clusters = catalog.thermal.positive(feature['cluster-count'])
            count = catalog.thermal.positive(generator['cluster-size'])
            if count > 27:
                raise ValueError('Native scatter cube needs review')
            # Approximate expected attempts per 16x16 column over the inclusive band.
            scarcity = round(256 * (hi - lo + 1) * total / (clusters * weight))
            scatters.append({'ore': 'era_materials:' + native + '_ore', 'source_feature': name,
                             'min_layer': lo, 'max_layer': hi, 'scarcity': scarcity,
                             'count': count, 'size': 3})
    cooking = [{'input': 'era_materials:' + name + '_dust', 'output': ingot,
                'seconds': review['native_cooking_seconds']}
               for name, ingot in review['cooking'].items()]
    processing = []
    inputs = {'oreCopper': 'mcl_copper:stone_with_copper', 'oreTin': 'era_materials:tin_ore',
              'oreSilver': 'era_materials:silver_ore', 'oreLead': 'era_materials:lead_ore'}
    for row in spec['processing_and_fuel']:
        if row['machine'] != 'pulverizer' or row['input']['id'] not in inputs:
            continue
        output = catalog.mapped(catalog.identity(row['output']), mapping['mappings'])
        secondary = row['secondary']
        processing.append({'input': inputs[row['input']['id']],
                           'output': output + ' ' + str(row['output']['count']),
                           'cost': row['energy_rf'],
                           'secondary_output': catalog.mapped(catalog.identity(secondary['stack']), mapping['mappings']),
                           'secondary_chance': secondary['chance_percent']})
    if len(processing) != len(inputs):
        raise ValueError('Missing selected ore recipe')
    for name, ingot in review['pulverizer_ingots'].items():
        processing.append({'input': ingot, 'output': 'era_materials:' + name + '_dust', 'cost': 2000})
    return {'schema': 1, 'review_sha256': reference.sha256(reference.canonical(review)),
            'spec_sha256': reference.sha256(reference.canonical(spec)),
            'mapping_sha256': reference.sha256(reference.canonical(mapping)),
            'ores': ores, 'scatters': scatters, 'cooking': cooking, 'pulverizing': processing}


def render(value):
    return '-- SPDX-License-Identifier: GPL-3.0-or-later\n-- Generated by scripts/thermal_survival.py; native placement approximates source bands/density.\nreturn ' + catalog.lua(value) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('check', 'check-sources', 'export'))
    args = parser.parse_args()
    review = json.loads(REVIEW.read_text())
    mapping = json.loads(catalog.REVIEW.read_text())
    if args.command == 'check-sources':
        catalog.verify_sources(mapping)
        source = review['config']
        entry = next(e for e in reference.read_lock()['content']['files'] if e['path'] == source['path'])
        raw = reference.destination(entry).read_bytes()
        reference.verify(entry, raw)
        if source['sha256'] != reference.sha256(raw):
            raise ValueError('Stale survival config review')
        value = json.loads(raw)['populate']
        if any(value[key] != feature for key, feature in review['ore_features'].items()):
            raise ValueError('Changed selected ore-generation records')
        print('SURVIVAL SOURCE PASS: locked ore config and reviewed classes match originals')
        return
    rendered = render(compile_survival(review, json.loads(catalog.SPEC.read_text()), mapping))
    if args.command == 'export':
        print(rendered, end='')
    elif rendered != OUTPUT.read_text():
        raise ValueError('Survival definitions are stale; regenerate and review')
    else:
        print('SURVIVAL MODEL PASS: three ores, five scatters, eight dust cooking and six pulverizing records')


if __name__ == '__main__':
    main()
